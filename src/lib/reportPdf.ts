/**
 * Builds the downloadable report PDF from the stored results. This stands in
 * for the LIS's own signed PDF (the brief says to mock outside systems).
 *
 * English only, with the PDF standard fonts: no font files to embed keeps the
 * download small on weak data. Characters those fonts can't draw are replaced.
 */

import { PDFDocument, rgb, StandardFonts, type PDFFont, type PDFPage } from "pdf-lib";
import type { ResultFlag } from "./flags";

export type ReportPdfInput = {
  labName: string;
  patientName: string;
  lisOrderId: string;
  referringDoctor: string;
  signedAt: Date | null;
  critical: boolean;
  results: Array<{ parameter: string; valueText: string; unit: string; refText: string; flag: ResultFlag }>;
};

const FLAG_WORDS: Record<ResultFlag, string> = {
  NORMAL: "Normal",
  LOW: "Low",
  HIGH: "High",
  CRITICAL_LOW: "CRITICAL (low)",
  CRITICAL_HIGH: "CRITICAL (high)",
  UNKNOWN: "-",
};

const REPLACEMENTS: Record<string, string> = { "≤": "<=", "≥": ">=", "–": "-", "—": "-", "’": "'", "“": '"', "”": '"' };

/** The standard PDF fonts only cover Latin-1; anything else would make pdf-lib throw. */
export function pdfSafe(text: string): string {
  return [...text].map((ch) => REPLACEMENTS[ch] ?? (ch.charCodeAt(0) <= 0xff ? ch : "?")).join("");
}

const PAGE = { width: 595.28, height: 841.89, margin: 48 }; // A4 in points
const INK = rgb(0.04, 0.16, 0.18);
const MUTED = rgb(0.27, 0.38, 0.37);
const RED = rgb(0.56, 0.11, 0.11);
const COLUMNS = [
  { label: "Test", x: 0, width: 170 },
  { label: "Result", x: 175, width: 80 },
  { label: "Unit", x: 260, width: 70 },
  { label: "Reference range", x: 335, width: 100 },
  { label: "Flag", x: 440, width: 59 },
];

function fit(text: string, font: PDFFont, size: number, width: number): string {
  let out = pdfSafe(text);
  if (font.widthOfTextAtSize(out, size) <= width) return out;
  while (out.length > 1 && font.widthOfTextAtSize(`${out}...`, size) > width) out = out.slice(0, -1);
  return `${out}...`;
}

export async function buildReportPdf(input: ReportPdfInput): Promise<Uint8Array> {
  const pdf = await PDFDocument.create();
  pdf.setTitle(`Test report ${input.lisOrderId}`);
  pdf.setProducer("Clara");
  const regular = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);

  let page: PDFPage = pdf.addPage([PAGE.width, PAGE.height]);
  let y = PAGE.height - PAGE.margin;
  const left = PAGE.margin;

  const text = (value: string, x: number, size: number, font = regular, color = INK) =>
    page.drawText(pdfSafe(value), { x, y, size, font, color });

  text(input.labName, left, 18, bold);
  y -= 22;
  text("Test report", left, 12, regular, MUTED);
  y -= 30;

  const signed = input.signedAt
    ? new Intl.DateTimeFormat("en-IN", { dateStyle: "medium", timeStyle: "short", timeZone: "Asia/Kolkata" }).format(input.signedAt)
    : "Not signed";
  for (const [label, value] of [
    ["Patient", input.patientName],
    ["Order", input.lisOrderId],
    ["Referring doctor", input.referringDoctor],
    ["Signed", `${signed} IST`],
  ]) {
    text(label, left, 10, regular, MUTED);
    text(value, left + 110, 10, bold);
    y -= 16;
  }

  if (input.critical) {
    y -= 8;
    text("CRITICAL RESULT: the lab will contact the patient by phone.", left, 11, bold, RED);
    y -= 8;
  }

  const drawHeader = () => {
    y -= 22;
    for (const col of COLUMNS) text(col.label, left + col.x, 9, bold, MUTED);
    y -= 6;
    page.drawLine({ start: { x: left, y }, end: { x: PAGE.width - left, y }, thickness: 0.75, color: MUTED });
    y -= 16;
  };
  drawHeader();

  for (const r of input.results) {
    if (y < PAGE.margin + 60) {
      page = pdf.addPage([PAGE.width, PAGE.height]);
      y = PAGE.height - PAGE.margin;
      text(`${input.lisOrderId} (continued)`, left, 10, regular, MUTED);
      drawHeader();
    }
    const critical = r.flag === "CRITICAL_LOW" || r.flag === "CRITICAL_HIGH";
    const cells = [r.parameter, r.valueText, r.unit || "-", r.refText || "-", FLAG_WORDS[r.flag]];
    cells.forEach((cell, i) => {
      const font = i === 1 || critical ? bold : regular;
      page.drawText(fit(cell, font, 10, COLUMNS[i].width), {
        x: left + COLUMNS[i].x,
        y,
        size: 10,
        font,
        color: critical && i === 4 ? RED : INK,
      });
    });
    y -= 18;
  }

  const footer = [
    "Generated by Clara from the lab's signed results. Demo document standing in for the LIS signed PDF.",
    "Explanation of results is not a diagnosis. Please discuss this report with your doctor.",
  ];
  for (const p of pdf.getPages()) {
    footer.forEach((line, i) =>
      p.drawText(line, { x: left, y: PAGE.margin - 12 - i * 11, size: 8, font: regular, color: MUTED }),
    );
  }

  return pdf.save();
}
